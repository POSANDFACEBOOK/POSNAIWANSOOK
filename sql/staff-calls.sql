create table if not exists public.staff_calls (
  id           bigint generated by default as identity primary key,
  branch_id    bigint not null,
  table_id     bigint not null,
  table_number text,                       -- ที่มือถือลูกค้าเห็น (ใบพิมพ์ใช้ชื่อโต๊ะจากตาราง tables ไม่ใช่ช่องนี้)
  token        text,                       -- รหัส QR ที่ลูกค้าสแกน — ตัวพิมพ์เทียบกับ tables.qr_token ก่อนพิมพ์
  status       text not null default 'new',
  created_at   timestamptz not null default now(),
  done_at      timestamptz,
  printers     int,                        -- พิมพ์ออกกี่เครื่อง
  note         text                        -- เหตุผล/รหัสเครื่องตัวพิมพ์ที่จอง (ไว้ไล่ย้อนหลัง)
);

-- ตัวพิมพ์ถามเฉพาะแถว 'new' ของสาขาตัวเองทุก 2 วิ — ดัชนีบางส่วนเล็กมาก ปกติว่าง (ไม่กิน Disk IO)
create index if not exists staff_calls_new_idx on public.staff_calls (branch_id, id) where status = 'new';

alter table public.staff_calls disable row level security;
grant select, insert, update on public.staff_calls to anon, authenticated;

-- ให้ API (PostgREST) เห็นตารางใหม่ทันที ไม่ต้องรอ
notify pgrst, 'reload schema';

