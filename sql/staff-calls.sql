-- รันใน Supabase → SQL Editor ครั้งเดียว (รันซ้ำได้ — IF NOT EXISTS)
-- ⚠️ รันหลัง deploy โค้ดชุดนี้แล้วเท่านั้น — ตัวสำรองข้อมูลรายคืน (api/backup.js) รุ่นก่อนหน้าไม่รู้จักตารางนี้
--    เจอตารางใหม่แล้วจะบันทึกคืนนั้นว่า "ไม่ครบ" (รุ่นใหม่ข้ามตารางนี้โดยเจตนา — คิวอายุ 90 วิ ไม่ต้องสำรอง)
--
-- ลูกค้ากดปุ่ม → แอปเพิ่มแถวในตารางนี้ (status 'new')
-- ตัวพิมพ์ของสาขา (print-agent v49) ถามทุก 2 วินาที → จองแถว ('printing') → พิมพ์ใบ
-- "เรียกพนักงาน · โต๊ะ X" ที่เครื่องที่ติ๊กเป็นเครื่องพิมพ์ใบเสร็จเท่านั้น → จดผลกลับ
--   printed  = ออกอย่างน้อยหนึ่งเครื่อง
--   failed   = ส่งไม่ออกทุกเครื่อง / สาขาไม่มีเครื่องใบเสร็จ (ขึ้นในปุ่ม "พิมพ์ไม่สำเร็จ" ที่จอขาย)
--   merged   = โต๊ะนี้เพิ่งเรียกไปไม่ถึง 1 นาที — ไม่พิมพ์ซ้ำ
--   rejected = QR ไม่ตรงโต๊ะ/โต๊ะปิดใช้ · expired = ตัวพิมพ์เห็นช้าเกิน 90 วิ (ดับอยู่) ไม่พิมพ์ย้อนหลัง
--              หรือหน้าลูกค้ารอครบ 30 วิแล้วปิดเอง (เฉพาะแถวที่ยัง new — ตัวพิมพ์จองด้วยเงื่อนไขเดียวกัน จึงไม่มีใบออกตามมาทีหลัง)
-- หน้าลูกค้าอ่านสถานะของแถวตัวเองไม่กี่ครั้งหลังกด แล้วบอกตามจริงว่า "แจ้งแล้ว" หรือ "โบกมือเรียก"
--
-- ทำไมเป็นตารางใหม่ ไม่ใช้ช่องคำสั่งในแถวเครื่องพิมพ์ (description.pj):
--   ช่องนั้นมีที่เดียวต่อเครื่อง และแอปเขียนแบบ อ่าน-แก้-เขียนทับทั้งก้อน — มือถือลูกค้าเขียนคั่น
--   จังหวะเดียวกับแคชเชียร์สั่งพิมพ์ใบเสร็จ = ใบเสร็จหายเงียบ · ตารางนี้เพิ่มแถวอย่างเดียว ไม่ทับใคร
--
-- ⚠️ Supabase เปิด RLS ให้ตารางใหม่อัตโนมัติ → ต้องปิด (ระบบนี้คุมสิทธิ์ที่ชั้นแอปทุกตาราง)
-- ก่อนรัน: ปุ่มเรียกพนักงานในหน้าลูกค้าขึ้นว่า "แจ้งผ่านระบบไม่สำเร็จ — กรุณาโบกมือเรียก" · อย่างอื่นปกติ
