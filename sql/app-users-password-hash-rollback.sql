-- ถอยกลับ: คืนสิทธิ์อ่านทั้งตาราง app_users (31 ต.ค. 69) — คู่กับ sql/app-users-password-hash.sql
--
-- ⚠️ ก่อนใช้ไฟล์นี้ อ่านข้อนี้ก่อน:
--   • จอขึ้นว่าอ่าน/บันทึกข้อมูลผู้ใช้ไม่ได้เพราะขอคอลัมน์ใหม่ที่ยังไม่ได้ให้สิทธิ์ = ไม่ต้องใช้ไฟล์นี้
--     ให้รันเฉพาะคอลัมน์นั้น: grant select (ชื่อคอลัมน์) on table public.app_users to anon, authenticated;
--     (แล้วเพิ่มชื่อนั้นใน APP_USER_COLS + grant ใน sql/app-users-password-hash.sql)
--   • จอที่ยังเป็นโค้ดเก่า (ก่อน 31 ต.ค. 69) = แค่รีเฟรช/ปิดเปิดแอปเครื่องนั้น ไม่ต้องใช้ไฟล์นี้
--   • เข้าระบบไม่ได้ทั้งร้านหลัง Instant Rollback / redeploy Vercel ไปเวอร์ชันก่อน 31 ต.ค. 69 = ไฟล์นี้ "แก้ไม่ได้"
--     (รหัสเป็น bcrypt แล้ว โค้ดเก่าเทียบตัวหนังสือ) ทางแก้ทางเดียวคือ Promote/redeploy เวอร์ชันที่มี rpc/app_login กลับขึ้นมา
--
-- ใช้เมื่อ: หลังรันไฟล์หลักแล้วมีจอไหนพังเพราะอ่าน app_users ไม่ได้ และแก้ด้วยข้อข้างบนไม่ได้ (ฉุกเฉินเท่านั้น)
-- ทำแค่: grant select ทั้งตารางคืนให้ anon/authenticated (เหมือนก่อนรันไฟล์หลัก) แล้วให้ PostgREST โหลดโครงสร้างใหม่
--
-- สิ่งที่ "ไม่" ถอย (ตั้งใจ):
--   • รหัสผ่านยังเป็น bcrypt — ย้อนเป็นตัวหนังสือไม่ได้ (bcrypt ทางเดียว)
--   • ตัวกัน (trigger) และ app_login ยังอยู่ ⟹ แอปเวอร์ชัน 31 ต.ค. 69 ขึ้นไปเข้าระบบผ่าน app_login ได้ตามปกติ
--   • แอปเวอร์ชันก่อน 31 ต.ค. 69 (เทียบรหัสตัวหนังสือตรงๆ) เข้าระบบไม่ได้แม้ถอยแล้ว — ถ้าต้องถอยแอปด้วยจริงๆ
--     ต้อง drop trigger app_users_hash_password แล้วตั้งรหัสตัวหนังสือใหม่ให้ทุกคน (ไม่แนะนำ)
-- ⚠️ ถอยแล้วทุกเครื่องอ่าน bcrypt ของทุกคนได้อีก (เอาไปเดารหัสแบบออฟไลน์ได้) — แก้จอที่พังแล้วรันไฟล์หลักใหม่โดยเร็ว
--    (ระหว่างนี้การสำรองทุกคืนจะขึ้น "สำเร็จ (มีเตือน)" + แจ้งแอดมิน ว่า password อ่านได้ด้วยคีย์สาธารณะ — ตั้งใจ)
--
-- วิธีใช้: Supabase → SQL Editor → วางทั้งไฟล์นี้ → Run (รันซ้ำได้)
-- ════════════════════════════════════════════════════════════════════════
begin;
grant select on table public.app_users to anon, authenticated;
notify pgrst, 'reload schema';
commit;

-- ผล: true = anon อ่านทั้งตารางได้อีกแล้ว (ถอยสำเร็จ) · login_fn ยัง true
select has_column_privilege('anon', 'public.app_users', 'password', 'SELECT') as anon_reads_password,
       coalesce(has_function_privilege('anon', to_regprocedure('public.app_login(text, text)'), 'EXECUTE'), false) as login_fn;
