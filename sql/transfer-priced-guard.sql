-- แอปไม่รีโหลดเอง พนักงานเปิดหน้า PO ค้างทั้งวัน ⟹ เครื่องที่ยังรันเวอร์ชันก่อนคิดเงิน กด "รับโอน"
-- ใบโอนที่มียอดแล้วจะเขียน status=transfer_done โดยยอดยังเป็นยอดตอนสั่ง และไม่ส่งบัญชี (หนี้หายเงียบ)
-- ด่านนี้ทำให้คำสั่งนั้นล้มตั้งแต่ขั้นแรก — โค้ดรับโอนทั้งเก่าและใหม่เปลี่ยนสถานะ "ก่อน" ขยับสต๊อก
-- จึงไม่มีสต๊อกขยับค้าง พนักงานเห็นข้อความผิดพลาด → รีโหลด → เวอร์ชันใหม่รับโอนได้ถูกต้อง
--
-- ปลอดภัยกับข้อมูลเดิม: ใบโอนเก่าทั้งหมดยอด 0 (ตรวจ 13 ต.ค. 69: transfer_done ที่ยอด > 0 = 0 ใบ)
-- โค้ดใหม่: ใบคิดเงิน → awaiting_payment/paid · ใบเก่า ฿0 → transfer_done (ยอด 0) ไม่ชนด่าน
-- ถ้ามีใบหลุดมาก่อนรันด่าน หน้า PO ของเวอร์ชันใหม่ซ่อมให้เอง (staleTransferHealPatch) — ALTER จะล้มถ้ายังมีค้าง
-- ให้เปิดหน้า PO ของสาขานั้นหนึ่งครั้งแล้วรันใหม่
-- ══════════════════════════════════════════════════════════════════════════

alter table public.purchase_orders
  add constraint tr_priced_not_done
  check (not (po_number like 'TR-%' and status = 'transfer_done' and coalesce(total, 0) > 0));
