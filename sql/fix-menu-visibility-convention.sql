-- ═══════════════════════════════════════════════════════════════════════════
-- แก้กติกา visible_branches ของเมนูให้ตรงกับวัตถุดิบ
--
-- ปัญหา: ของเมนู "[] ว่าง" เคยแปลว่า "เปิดให้ทุกสาขา" และไม่มีค่าไหนเลย
-- ที่แปลว่า "ไม่เปิดให้สาขาไหน" — ปุ่มติ๊กจึงพังโดยธรรมชาติ:
--   ติ๊กออกทีละสาขาจนหมด → ค่ากลายเป็น [] → เมนูกลับไปโผล่ทุกสาขา (ตรงข้ามกับที่ตั้งใจ)
--
-- กติกาใหม่ (เหมือนวัตถุดิบ):
--   null   = เปิดให้ทุกสาขา
--   []     = ไม่เปิดให้สาขาไหนเลย
--   [ids]  = เฉพาะสาขาที่ระบุ
--
-- ⚠️ ต้องรัน SQL นี้ "ก่อน" ขึ้นเวอร์ชันใหม่
-- เพราะเมนูที่เป็น [] อยู่ตอนนี้ (33 รายการ เช่น น้ำเปล่า โซดา เป๊ปซี่ น้ำแข็ง รีฟิล)
-- ถ้าโค้ดใหม่ขึ้นก่อน จะถูกตีความว่า "ปิดทุกสาขา" แล้วหายจาก POS ทุกสาขาทันที
--
-- คำสั่งนี้แปลง [] → null = "เปิดให้ทุกสาขา" ซึ่งเป็นพฤติกรรมเดิมเป๊ะ
-- (ทั้งโค้ดเก่าและโค้ดใหม่อ่านค่า null เหมือนกัน จึงรันตอนไหนก็ปลอดภัย)
--
-- 📌 หลังรันเสร็จ: เมนู 33 ตัวนี้จะอยู่ในสถานะ "เปิดให้ทุกสาขา"
--    ถ้ามีตัวไหนที่ตั้งใจจะปิดไว้ ให้ไปติ๊กออกใหม่ในแอป — คราวนี้จะปิดได้จริง
-- ═══════════════════════════════════════════════════════════════════════════

-- สำรองไว้ก่อน
create table if not exists _backup_menu_vb_20690827 as
select id, name, visible_branches from menus where visible_branches = '[]'::jsonb;

select count(*) as "เมนูที่จะแปลง" from _backup_menu_vb_20690827;

-- แปลง [] → null
update menus set visible_branches = null where visible_branches = '[]'::jsonb;

-- ตรวจผล: ทั้ง 3 ช่องต้องเป็น 0
select
  (select count(*) from menus where visible_branches = '[]'::jsonb) as "ยังเหลือ_ว่าง",
  (select count(*) from menus m join _backup_menu_vb_20690827 b on b.id = m.id
     where m.visible_branches is not null) as "แปลงไม่สำเร็จ",
  (select count(*) from menus where visible_branches is not null
     and jsonb_typeof(visible_branches) <> 'array') as "ชนิดข้อมูลผิด";

-- รายชื่อเมนูที่ตอนนี้ "เปิดให้ทุกสาขา" — ตรวจว่ามีตัวไหนที่ควรปิดไหม
select id, name, price, category from _backup_menu_vb_20690827 order by name;
