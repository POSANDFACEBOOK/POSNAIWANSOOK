patched as (
  select a.ing_id,
         jsonb_object_agg(
           a.branch_id::text,
           to_jsonb(greatest(0, round((coalesce((i.stock_by_branch->>a.branch_id::text)::numeric, 0) + a.delta)::numeric, 3)))
         ) as patch
  from adj a
  join ingredients i on i.id = a.ing_id
  group by a.ing_id
)
update ingredients i
set stock_by_branch = coalesce(i.stock_by_branch, '{}'::jsonb) || p.patch
from patched p
where i.id = p.ing_id;

