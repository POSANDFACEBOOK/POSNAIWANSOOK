  M01: ACC.MEAT, M02: ACC.FROZEN, M03: ACC.VEG, M04: ACC.OTHER, M05: ACC.OTHER,
  D01: ACC.DRY, D02: ACC.SEASONING, D03: ACC.DESSERT,
