#!/data/data/com.termux/files/usr/bin/sh
# ════════════════════════════════════════════════════════════════════════
#  FOODCOST — ติดตั้งตัวพิมพ์บนมือถือ Android (แอป Termux) ด้วยคำสั่งเดียว
#
#  พิมพ์ในแอป Termux บนมือถือ (เลขท้ายสุด = เลขสาขา):
#     curl -L foodcost-eta.vercel.app/setup.sh | sh -s 5
#
#  ทำให้ครบในครั้งเดียว: ติดตั้ง nodejs + curl · จำเลขสาขา · โหลดตัวเรียกใช้งาน (agent-run.sh)
#  · ตั้งให้ตัวพิมพ์เปิดเองตอนมือถือเปิดเครื่อง (ต้องมีแอป Termux:Boot และเปิดมันสักครั้ง) · เริ่มตัวพิมพ์
#  รันซ้ำได้ทุกเมื่อ (เช่น ติดตั้งค้างกลางทาง) — ย้ายมือถือไปสาขาอื่น = ล้างความจำการพิมพ์ของสาขาเดิมให้เอง
#  ที่มา: พนักงานพิมพ์คำสั่ง 7 บรรทัดบนจอมือถือไม่ไหว (ติดตั้งสาขา 5 กาญจนบุรี 19 ต.ค. 69)
# ════════════════════════════════════════════════════════════════════════
# ทั้งสคริปต์อยู่ในฟังก์ชัน main — sh ต้องอ่านไฟล์จนจบก่อนเริ่มทำงาน
# (รันแบบ curl | sh ถ้ามีคำสั่งไหนอ่านจากแป้นพิมพ์ มันจะกินบรรทัดที่เหลือของสคริปต์ไปแทน แล้วติดตั้งไม่ครบ)
main() {
  BR="$(printf '%s' "$1" | tr -dc '0-9')"
  # ไม่มีค่าเริ่มต้น — ลืมใส่เลขแล้วแอบติดตั้งเป็นสาขาอื่น = พิมพ์ใบผิดร้าน
  if [ -z "$BR" ]; then
    echo "❌ ต้องใส่เลขสาขาไว้ท้ายคำสั่ง เช่น สาขากาญจนบุรี (5):"
    echo "   curl -L foodcost-eta.vercel.app/setup.sh | sh -s 5"
    exit 2
  fi
  BASE="https://foodcost-eta.vercel.app"
  echo "════════════════════════════════════════"
  echo " ติดตั้งตัวพิมพ์ FOODCOST — สาขา $BR"
  echo " ใช้เวลาหลายนาที อย่าปิดแอประหว่างนี้"
  echo "════════════════════════════════════════"

  echo "① ติดตั้งโปรแกรมที่ต้องใช้ (nodejs, curl)..."
  # yes = ตอบ "ใช่" ให้ทุกคำถามระหว่างติดตั้ง (คำถามเรื่องไฟล์ตั้งค่า ฯลฯ) พนักงานไม่ต้องกดอะไร
  yes | pkg upgrade -y
  if ! yes | pkg install -y nodejs-lts curl; then
    echo "❌ ติดตั้ง nodejs ไม่สำเร็จ — เช็กว่ามือถือต่อเน็ตอยู่ แล้วพิมพ์คำสั่งเดิมอีกครั้ง"
    exit 1
  fi
  if ! command -v node >/dev/null 2>&1; then
    echo "❌ ติดตั้งแล้วแต่ไม่เจอ node — ถ่ายรูปจอนี้ส่งผู้ดูแลระบบ"
    exit 1
  fi

  echo "② ตั้งเลขสาขา = $BR"
  OLD="$(cat "$HOME/.foodcost-branch" 2>/dev/null | tr -dc '0-9')"
  # มือถือเคยใช้กับสาขาอื่น: ความจำว่า "พิมพ์บิลไหนไปแล้ว" เป็นของสาขาเดิม — ลบทิ้ง
  # ตัวพิมพ์จะจดบิลที่ค้างอยู่ของสาขาใหม่ว่าเห็นแล้วโดยไม่พิมพ์ (ไม่มีใบเก่าทะลักออกมา)
  if [ -n "$OLD" ] && [ "$OLD" != "$BR" ]; then
    rm -f "$HOME/.foodcost-printed.json"
    echo "   (มือถือเคยใช้กับสาขา $OLD — ล้างความจำการพิมพ์ของสาขาเดิมแล้ว)"
  fi
  echo "$BR" > "$HOME/.foodcost-branch"

  echo "③ โหลดตัวเรียกใช้งาน + ตั้งให้เปิดเองตอนเปิดเครื่อง..."
  cd "$HOME" || exit 1
  if ! curl -fsSL -o "$HOME/agent-run.sh" "$BASE/agent-run.sh" || [ ! -s "$HOME/agent-run.sh" ]; then
    echo "❌ โหลดตัวเรียกใช้งานไม่ได้ — เช็กเน็ต แล้วพิมพ์คำสั่งเดิมอีกครั้ง"
    exit 1
  fi
  mkdir -p "$HOME/.termux/boot"
  if curl -fsSL -o "$HOME/.termux/boot/boot-agent.sh" "$BASE/boot-agent.sh" && [ -s "$HOME/.termux/boot/boot-agent.sh" ]; then
    chmod +x "$HOME/.termux/boot/boot-agent.sh"
  else
    echo "⚠️  ตั้งให้เปิดเองตอนเปิดเครื่องไม่สำเร็จ — ตัวพิมพ์ยังใช้ได้ แต่ถ้ามือถือรีสตาร์ท ต้องเปิด Termux แล้วพิมพ์: sh agent-run.sh"
  fi

  echo "════════════════════════════════════════"
  echo " ✅ ติดตั้งเสร็จ — กำลังเริ่มตัวพิมพ์"
  echo " • ปล่อยแอป Termux เปิดไว้ ไม่ต้องกดออก"
  echo " • ตั้งแบตเตอรี่ของ Termux และ Termux:Boot เป็น \"ไม่จำกัด\""
  echo " • ถ้ามือถือรีสตาร์ทแล้วตัวพิมพ์ไม่ขึ้นเอง: เปิด Termux แล้วพิมพ์  sh agent-run.sh"
  echo "════════════════════════════════════════"
  exec sh "$HOME/agent-run.sh" "$BR"
}
main "$@"
